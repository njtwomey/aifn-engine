/**
 * `node scripts/svm-surface.ts`: tabulate the cross-validated error of an RBF support vector machine over a grid of
 * $\log_{10} C$ and $\log_{10}\gamma$, once, so that `svmTuningSurface` (`aifn-methods/data/objectives`) and the
 * figures built on it are instant.
 *
 * - Data: Fisher's iris, versicolor (label 0) against virginica (label 1), 100 flowers and four measurements, each
 *   standardised by its mean and population standard deviation over the 100 rows.
 * - Model: `supportVectorMachine` (`aifn-methods/learning/kernel-methods`) with $C$ and the RBF kernel
 *   $\exp(-\gamma \lVert \xvec - \xvec' \rVert^2)$, that is `rbf` with lengthscale $1 / \sqrt{2\gamma}$.
 * - Validation: `crossValidate` (`aifn-compute/learning/validate`) with ten repeats of shuffled stratified 5-fold, the
 *   same splits for every cell (one stream), scored by `errorRate`; the table holds the mean over the 50 folds and
 *   their standard deviation.
 * - Grid: $\log_{10} C$ from $-2$ to 3 and $\log_{10}\gamma$ from $-3$ to 2, in steps of $\tfrac14$ (21 by 21).
 *
 * The engine's source is TypeScript with extensionless imports, so it is loaded through Vite's SSR loader (as
 * `examples/check.ts` does). It writes `packages/methods/src/data/objectives/svm-table.ts`, formatted by Prettier, and takes
 * a minute or two.
 */
import fs from 'node:fs'
import path from 'node:path'
import { format, resolveConfig } from 'prettier'
import { createServer } from 'vite'

const root = path.join(import.meta.dirname, '..')
const out = path.join(root, 'packages', 'methods', 'src', 'data', 'objectives', 'svm-table.ts')

const LOG_C = Array.from({ length: 21 }, (_, i) => -2 + i / 4)
const LOG_GAMMA = Array.from({ length: 21 }, (_, i) => -3 + i / 4)
const FOLDS = 5
const REPEATS = 10
const SEED = 'svm-surface'

const server = await createServer({
  root,
  configFile: false,
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false, watch: null, ws: false },
  appType: 'custom',
})
try {
  const load = (id: string) => server.ssrLoadModule(id) as Promise<Record<string, any>>
  const { iris } = await load('aifn-methods/data/real')
  const { supportVectorMachine } = await load('aifn-methods/learning/kernel-methods')
  const { crossValidate, repeated, stratifiedKFold } = await load('aifn-compute/learning/validate')
  const { errorRate } = await load('aifn-compute/learning/metrics')
  const { stream } = await load('aifn-compute/foundation/random')
  const { rbf } = await load('aifn-compute/learning/kernels')
  const { tensor, toArray } = await load('aifn-compute/foundation/tensor')

  // Versicolor and virginica: rows 50 to 149, labels 1 and 2 shifted to 0 and 1.
  const data = iris()
  const rows = (toArray(data.x) as number[][]).slice(50)
  const labels = (toArray(data.y) as number[]).slice(50).map((v) => v - 1)
  const d = rows[0].length
  const centre = Array.from({ length: d }, (_, j) => rows.reduce((s, r) => s + r[j], 0) / rows.length)
  const spread = Array.from({ length: d }, (_, j) =>
    Math.sqrt(rows.reduce((s, r) => s + (r[j] - centre[j]) ** 2, 0) / rows.length),
  )
  const x = tensor(rows.map((r) => r.map((v, j) => (v - centre[j]) / spread[j])))
  const y = tensor(labels)

  const error: number[][] = []
  const sd: number[][] = []
  const start = performance.now()
  for (const logC of LOG_C) {
    const errorRow: number[] = []
    const sdRow: number[] = []
    for (const logGamma of LOG_GAMMA) {
      const estimator = supportVectorMachine({
        C: 10 ** logC,
        kernel: rbf({ lengthscale: 1 / Math.sqrt(2 * 10 ** logGamma) }),
      })
      const cv = crossValidate(
        estimator,
        { x, y },
        repeated(stratifiedKFold({ k: FOLDS, shuffle: true }), REPEATS),
        [errorRate],
        {
          stream: stream(SEED),
        },
      )
      errorRow.push(Number(cv.mean.errorRate.toFixed(10)))
      sdRow.push(Number(cv.std.errorRate.toFixed(6)))
    }
    error.push(errorRow)
    sd.push(sdRow)
    console.log(`log10 C = ${logC.toFixed(2)}: ${errorRow.map((e) => e.toFixed(3)).join(' ')}`)
  }
  console.log(`${((performance.now() - start) / 1000).toFixed(0)} s`)

  const list = (v: number[]) => `[${v.join(', ')}]`
  const table = (m: number[][]) => `[\n${m.map((r) => `    ${list(r)},`).join('\n')}\n  ]`
  const text = `/**
 * Generated by \`node scripts/svm-surface.ts\`; do not edit. The validation error of an RBF support vector machine on
 * Fisher's iris (versicolor against virginica, standardised), by ${REPEATS} repeats of stratified ${FOLDS}-fold
 * cross-validation, on a grid of $\\log_{10} C$ and $\\log_{10}\\gamma$: the data of \`svmTuningSurface\`. The
 * script documents the settings.
 */

/** The tabulated surface: row $i$ is the $i$-th value of $\\log_{10} C$, column $j$ the $j$-th of $\\log_{10}\\gamma$. */
export const SVM_TABLE = {
  /** The values of $\\log_{10} C$, increasing and equally spaced. */
  logC: ${list(LOG_C)},
  /** The values of $\\log_{10}\\gamma$, increasing and equally spaced. */
  logGamma: ${list(LOG_GAMMA)},
  /** The mean validation error over the ${FOLDS * REPEATS} folds, one row per value of $C$. */
  error: ${table(error)},
  /** The standard deviation of the validation error over the folds, laid out as \`error\`. */
  sd: ${table(sd)},
} as const
`
  fs.writeFileSync(out, await format(text, { ...(await resolveConfig(out)), filepath: out }))
  console.log(`wrote ${path.relative(root, out)}`)
} finally {
  await server.close()
}
